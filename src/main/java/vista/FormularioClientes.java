    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblClientes.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla.");
    return;
}

int codigo = Integer.parseInt(tblClientes.getValueAt(fila, 0).toString());

int confirmar = JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar este cliente?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
);

if (confirmar == JOptionPane.YES_OPTION) {
    controlador.eliminarCliente(codigo);
    modeloTabla.removeRow(fila);

    JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente.");

    btnLimpiarActionPerformed(evt);
}
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
      int fila = tblClientes.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla.");
    return;
}

txtCodigo.setText(tblClientes.getValueAt(fila, 0).toString());
txtNombre.setText(tblClientes.getValueAt(fila, 1).toString());
txtIdentidad.setText(tblClientes.getValueAt(fila, 2).toString());
txtTelefono.setText(tblClientes.getValueAt(fila, 3).toString());
txtDireccion.setText(tblClientes.getValueAt(fila, 4).toString());

JOptionPane.showMessageDialog(this, "Modifique los datos y vuelva a presionar Modificar.");
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnResgitrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResgitrarActionPerformed
        try {
    if (txtCodigo.getText().trim().isEmpty()
            || txtNombre.getText().trim().isEmpty()
            || txtIdentidad.getText().trim().isEmpty()
            || txtTelefono.getText().trim().isEmpty()
            || txtDireccion.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    int codigo = Integer.parseInt(txtCodigo.getText());

    modelo.Cliente cliente = new modelo.Cliente(
        codigo,
        txtNombre.getText(),
        txtIdentidad.getText(),
        txtTelefono.getText(),
        txtDireccion.getText()
    );

    controlador.registrarCliente(cliente);

    modeloTabla.addRow(new Object[]{
        codigo,
        txtNombre.getText(),
        txtIdentidad.getText(),
        txtTelefono.getText(),
        txtDireccion.getText()
    });

    JOptionPane.showMessageDialog(this, "Cliente registrado correctamente.");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "El código debe ser numérico.");
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnResgitrarActionPerformed

