    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
          try {
        if (txtNumeroFactura.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese el número de factura.");
            return;
        }

        if (cmbOrden.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccione una orden finalizada.");
            return;
        }

        int id = Integer.parseInt(txtNumeroFactura.getText().trim());

        if (controlador.buscarFactura(id) != null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Este número de factura ya existe.");
            return;
        }

        int idOrden = Integer.parseInt(
                cmbOrden.getSelectedItem().toString().split(" - ")[0]);

        modelo.OrdenTrabajo orden = ordenControlador.buscarOrden(idOrden);

        double subtotal = Double.parseDouble(txtSubtotal.getText());
        double impuesto = Double.parseDouble(txtImpuesto.getText());

        modelo.Factura factura = new modelo.Factura(
                id, orden, subtotal, impuesto, subtotal + impuesto);

        controlador.registrarFactura(factura);

        cargarFacturas();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Factura generada correctamente.");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Error al generar factura: " + e.getMessage());
    }

    }//GEN-LAST:event_btnGenerarActionPerformed

