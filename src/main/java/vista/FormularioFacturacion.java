    private void cmbOrdenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbOrdenActionPerformed
            if (cmbOrden.getSelectedItem() == null) {
        return;
    }

    try {
        String seleccion = cmbOrden.getSelectedItem().toString();
        int idOrden = Integer.parseInt(seleccion.split(" - ")[0]);

        modelo.OrdenTrabajo orden = ordenControlador.buscarOrden(idOrden);

        if (orden != null) {

            double subtotal = orden.getTotal();
            double impuesto = subtotal * 0.15;
            double total = subtotal + impuesto;

            txtCliente.setText(orden.getCliente().getNombre());

            txtVehiculo.setText(
                orden.getVehiculo().getMarca() + " " +
                orden.getVehiculo().getModelo()
            );

            txtSubtotal.setText(String.format("%.2f", subtotal));
            txtImpuesto.setText(String.format("%.2f", impuesto));
            txtTotal.setText(String.format("%.2f", total));
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Error al cargar la orden: " + e.getMessage());
    }

    }//GEN-LAST:event_cmbOrdenActionPerformed

