private void cargarOrdenes() {
    cmbOrden.removeAllItems();

    for (modelo.OrdenTrabajo orden : ordenControlador.listarOrdenes()) {
        if ("Finalizada".equals(orden.getEstado())) {
            cmbOrden.addItem(orden.getId() + " - " +
                    orden.getCliente().getNombre());
        }
    }
}

private void cargarFacturas() {
    modeloTabla.setRowCount(0);

    for (modelo.Factura factura : controlador.listarFacturas()) {
        modeloTabla.addRow(new Object[]{
            factura.getId(),
            factura.getOrden().getFecha(),
            factura.getOrden().getId(),
            factura.getOrden().getCliente().getNombre(),
            factura.getSubtotal(),
            factura.getImpuesto(),
            factura.getTotal()
        });
    }
}
