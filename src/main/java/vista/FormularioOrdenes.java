    private void tblOrdenesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrdenesMouseClicked
       int fila = tblOrdenes.getSelectedRow();

    if (fila == -1) {
        return;
    }

    int id = Integer.parseInt(
        tblOrdenes.getValueAt(fila, 0).toString()
    );

    modelo.OrdenTrabajo orden = controlador.buscarOrden(id);

    if (orden != null) {

        txtNumero.setText(String.valueOf(orden.getId()));
        txtFecha.setText(orden.getFecha());
        txtDescripcion.setText(orden.getDescripcion());

        cmbCliente.setSelectedItem(
            orden.getCliente().getId() + " - " +
            orden.getCliente().getNombre()
        );

        cmbVehiculo.setSelectedItem(
            orden.getVehiculo().getId() + " - " +
            orden.getVehiculo().getPlaca()
        );

        cmbServicio.setSelectedItem(
            orden.getServicio().getId() + " - " +
            orden.getServicio().getNombre()
        );

        cmbEstado.setSelectedItem(orden.getEstado());
    }

    }//GEN-LAST:event_tblOrdenesMouseClicked

    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
    int fila = tblOrdenes.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione una orden de la tabla.");
        return;
    }

    int id = Integer.parseInt(
            tblOrdenes.getValueAt(fila, 0).toString());

    modelo.OrdenTrabajo orden = controlador.buscarOrden(id);

    if (orden == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "No se encontró la orden.");
        return;
    }

    hilos.ProcesamientoOrden proceso =
            new hilos.ProcesamientoOrden(orden);

    proceso.start();

    javax.swing.JOptionPane.showMessageDialog(this,
            "El procesamiento de la orden ha iniciado.");

    }//GEN-LAST:event_btnProcesarActionPerformed

