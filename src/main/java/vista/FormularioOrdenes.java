   private void cargarOrdenes() {
    modeloTabla.setRowCount(0);

    for (modelo.OrdenTrabajo orden : controlador.listarOrdenes()) {

        modeloTabla.addRow(new Object[]{
            orden.getId(),
            orden.getCliente().getNombre(),
            orden.getVehiculo().getPlaca(),
            orden.getServicio().getNombre(),
            orden.getFecha(),
            orden.getEstado(),
            orden.getDescripcion()
        });
    }
}
   private void cargarClientes() {
    cmbCliente.removeAllItems();

    for (modelo.Cliente cliente : clienteControlador.listarClientes()) {
        cmbCliente.addItem(cliente.getId() + " - " + cliente.getNombre());
    }
}

private void cargarVehiculos() {
    cmbVehiculo.removeAllItems();

    for (modelo.Vehiculo vehiculo : vehiculoControlador.listarVehiculos()) {
        cmbVehiculo.addItem(vehiculo.getId() + " - " + vehiculo.getPlaca());
    }
}

private void cargarServicios() {
    cmbServicio.removeAllItems();

    for (modelo.Servicio servicio : servicioControlador.listarServicios()) {
        cmbServicio.addItem(servicio.getId() + " - " + servicio.getNombre());
    }
}

