    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
    if (cmbTipoReporte.getSelectedItem() == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un tipo de reporte.");
        return;
    }

    String tipo = cmbTipoReporte.getSelectedItem().toString();

    String[] etiquetas;
    double[] valores;

    if (tipo.toLowerCase().startsWith("orden")) {

        String[] estados = {
            "Pendiente", "En proceso", "Finalizada", "Cancelada"
        };

        etiquetas = estados;
        valores = new double[4];

        for (modelo.OrdenTrabajo orden : ordenControlador.listarOrdenes()) {
            for (int i = 0; i < estados.length; i++) {
                if (estados[i].equalsIgnoreCase(orden.getEstado())) {
                    valores[i]++;
                }
            }
        }

    } else {

        java.util.List<modelo.Factura> facturas =
                facturaControlador.listarFacturas();

        if (facturas.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No hay facturas registradas.");
            return;
        }

        etiquetas = new String[facturas.size()];
        valores = new double[facturas.size()];

        for (int i = 0; i < facturas.size(); i++) {
            modelo.Factura factura = facturas.get(i);
            etiquetas[i] = "Factura " + factura.getId();
            valores[i] = factura.getTotal();
        }
    }

    final String[] nombres = etiquetas;
    final double[] cantidades = valores;

    pnlGrafico.removeAll();
    pnlGrafico.setLayout(new java.awt.BorderLayout());
    pnlGrafico.setBackground(java.awt.Color.WHITE);

    javax.swing.JPanel grafico = new javax.swing.JPanel() {

        @Override
        protected void paintComponent(java.awt.Graphics g) {
            super.paintComponent(g);

            java.awt.Graphics2D g2 =
                    (java.awt.Graphics2D) g;

            g2.setRenderingHint(
                    java.awt.RenderingHints.KEY_ANTIALIASING,
                    java.awt.RenderingHints.VALUE_ANTIALIAS_ON);

            g2.setColor(java.awt.Color.BLACK);
            g2.drawString("REPORTE DE " + tipo.toUpperCase(), 20, 25);

            double maximo = 1;

            for (double valor : cantidades) {
                maximo = Math.max(maximo, valor);
            }

            int base = getHeight() - 50;
            int espacio = Math.max(1,
                    (getWidth() - 60) / cantidades.length);

            int anchoBarra = Math.max(15,
                    Math.min(45, espacio / 2));

            for (int i = 0; i < cantidades.length; i++) {

                int altura = (int) (
                        cantidades[i] / maximo * (getHeight() - 100));

                int x = 30 + i * espacio;
                int y = base - altura;

                g2.setColor(new java.awt.Color(52, 120, 180));
                g2.fillRect(x, y, anchoBarra, altura);

                g2.setColor(java.awt.Color.BLACK);
                g2.drawString(String.format("%.0f", cantidades[i]),
                        x, y - 8);

                g2.drawString(nombres[i], x, base + 20);
            }
        }
    };

    grafico.setBackground(java.awt.Color.WHITE);
    grafico.setPreferredSize(new java.awt.Dimension(500, 250));

    pnlGrafico.add(grafico, java.awt.BorderLayout.CENTER);

    pnlGrafico.revalidate();
    pnlGrafico.repaint();

    this.revalidate();
    this.repaint();

    }//GEN-LAST:event_btnGenerarActionPerformed

