    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
         try {
    int id = Integer.parseInt(txtId.getText());
    String nombre = txtNombre.getText();
    String marca = txtMarca.getText();
    int stock = Integer.parseInt(txtStock.getText());
    double precio = Double.parseDouble(txtPrecio.getText());

    if (nombre.isEmpty() || marca.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    if (id <= 0 || stock < 0 || precio <= 0) {
        JOptionPane.showMessageDialog(this, "Verifique los valores ingresados.");
        return;
    }

    if (controlador.buscarRepuesto(id) != null) {
        JOptionPane.showMessageDialog(this, "Ese ID ya existe.");
        return;
    }

    modelo.Repuesto repuesto = new modelo.Repuesto(
        id, nombre, marca, stock, precio
    );

    controlador.registrarRepuesto(repuesto);
    cargarRepuestos();

    JOptionPane.showMessageDialog(this, "Repuesto registrado correctamente.");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos en ID, Stock y Precio.");
}
            
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblRepuestos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un servicio de la tabla.");
            return;
        }

        int id = Integer.parseInt(
            tblRepuestos.getValueAt(fila, 0).toString()
        );

        int confirmar = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar este Repuesto?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {
            controlador.eliminarRepuesto(id);

            ((javax.swing.table.DefaultTableModel) tblRepuestos.getModel())
            .removeRow(fila);

            JOptionPane.showMessageDialog(this, "Repuesto eliminado correctamente.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

