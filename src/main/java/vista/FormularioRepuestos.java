  private void cargarRepuestos() {
    modeloTabla.setRowCount(0);

    for (modelo.Repuesto repuesto : controlador.listarRepuestos()) {
        modeloTabla.addRow(new Object[]{
            repuesto.getId(),
            repuesto.getNombre(),
            repuesto.getDescripcion(),
            repuesto.getCantidad(),
            repuesto.getPrecio()
        });
    }
} 

