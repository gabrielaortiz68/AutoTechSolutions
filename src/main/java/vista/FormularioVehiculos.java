    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
    String placa = txtPlaca.getText().trim();
    String marca = txtMarca.getText().trim();
    String modelo = txtModelo.getText().trim();
    int anio = Integer.parseInt(txtYear.getText().trim());

    if (placa.isEmpty() || marca.isEmpty() || modelo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    int codigo = Integer.parseInt(txtCodigoCliente.getText().trim());

    controlador.ClienteControlador clienteControlador =
            new controlador.ClienteControlador();

    modelo.Cliente cliente = clienteControlador.buscarCliente(codigo);

    if (cliente == null) {
        JOptionPane.showMessageDialog(this, "El cliente no existe.");
        return;
    }

    modelo.Vehiculo vehiculo = new modelo.Vehiculo(
            controlador.listarVehiculos().size() + 1,
            placa, marca, modelo, anio, cliente
    );

    controlador.registrarVehiculo(vehiculo);

    modeloTabla.addRow(new Object[]{
    codigo,
    marca,
    modelo,
    anio,
    txtColor.getText().trim(),
    placa
});

    JOptionPane.showMessageDialog(this, "Vehículo registrado correctamente.");
    txtPlaca.setText("");
    txtMarca.setText("");
    txtModelo.setText("");
    txtYear.setText("");
    txtColor.setText("");
    txtCodigoCliente.setText("");
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Verifique el año y el código del cliente.");
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblVehiculos.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un vehículo de la tabla.");
    return;
}

int confirmar = JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar este vehículo?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
);

if (confirmar == JOptionPane.YES_OPTION) {

  String placa = tblVehiculos.getValueAt(fila, 5).toString();

modelo.Vehiculo vehiculo = controlador.buscarPorPlaca(placa);

if (vehiculo != null) {
    controlador.eliminarVehiculo(vehiculo.getId());
}

    modeloTabla.removeRow(fila);

    JOptionPane.showMessageDialog(this, "Vehículo eliminado correctamente.");
}
    }//GEN-LAST:event_btnEliminarActionPerformed

